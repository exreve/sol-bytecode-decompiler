const ANCHOR_FEATURES = ['no-entrypoint = []', 'no-idl = []', 'no-log-ix-name = []', 'cpi = ["no-entrypoint"]', 'idl-build = []', 'anchor-debug = []', 'custom-heap = []', 'custom-panic = []']
const ERRORS = ['Math', 'Empty', 'Paused', 'Limit', 'Claimed', 'SameAccount', 'BadConfig', 'NoDest', 'BadDest', 'AlreadyInitialized', 'NotOpen']
const IDL_TY: Record<string, string> = { Pubkey: 'pubkey', u64: 'u64', u16: 'u16', u8: 'u8', bool: 'bool', i64: 'i64' }

const disc = (s: string) => [...createHash('sha256').update(s).digest().subarray(0, 8)]
const variantsOf = (p: Program) => p.units.flatMap(u => u.variants.map(v => ({ ...v, ix: u.name })))

function cargoToml(p: Program): string {
	const anchor = p.kind.startsWith('anchor')
	const feats = [...new Set(variantsOf(p).map(v => `v_${v.id} = []`))]
	const deps = p.kind === 'pinocchio' ? ['pinocchio = { workspace = true }']
		: p.kind === 'native' ? ['solana-program = { workspace = true }', ...(p.deps ?? [])]
		: ['anchor-lang = { workspace = true, features = ["init-if-needed"] }', 'anchor-spl = { workspace = true }', ...(p.kind === 'anchor29' ? ['solana-program = { workspace = true }'] : [])]
	return `# generated by bench/gen/gen.ts
[package]
name = "${p.name}"
version = "0.1.0"
edition = "2021"
rust-version = "1.84"

[lib]
crate-type = ["cdylib", "lib"]

[features]
default = []
${[...feats, ...(anchor ? ANCHOR_FEATURES : [])].join('\n')}

[dependencies]
${deps.join('\n')}
`
}

const indent = (s: string, t = '\t') => s.replace(/^(?=.)/gm, t)

function anchorLib(p: Program): string {
	const types = [...new Set(p.units.flatMap(u => u.types ?? []))]
	const token = p.units.some(u => /TokenAccount|token::/.test(u.code + u.accounts))
	return `// generated by bench/gen/gen.ts: ${p.about}; each v_* feature removes one property (bench/expected/${p.name}.json)
use anchor_lang::prelude::*;
${p.header ?? (token ? 'use anchor_spl::token::{self, Mint, Token, TokenAccount, Transfer};\n' : '')}
declare_id!("${p.id}");

#[program]
pub mod ${p.name} {
	use super::*;

${p.units.map(u => indent(u.code)).join('\n\n')}
}

${types.map(t => `#[account]\npub struct ${t} {\n${TYPES[t].fields.map(([n, ty]) => `\tpub ${n}: ${ty},`).join('\n')}\n}`).join('\n\n')}

${p.units.map(u => `#[derive(Accounts)]\n${u.accounts}`).join('\n\n')}

#[error_code]
pub enum GenError {
${[...ERRORS, ...p.errors ?? []].map(e => `\t${e},`).join('\n')}
}
`
}

function nativeLib(p: Program): string {
	return `// generated by bench/gen/gen.ts: ${p.about}; each v_* feature removes one property (bench/expected/${p.name}.json)
${p.header}
pub fn process(program_id: &Pubkey, accounts: &[AccountInfo], data: &[u8]) -> ProgramResult {
	match data.first() {
${p.units.map(u => `\t\tSome(${u.tag}) => ${u.name}(program_id, accounts, data),`).join('\n')}
		_ => Err(ProgramError::InvalidInstructionData),
	}
}

${p.units.map(u => u.code).join('\n\n')}
`
}

const idlAccounts = (s: string) => s.split(/\s+/).filter(Boolean).map(a => { const [name, f = ''] = a.split(':'); return { name, ...(f.includes('w') ? { writable: true } : {}), ...(f.includes('s') ? { signer: true } : {}) } })

function idl(p: Program): any {
	const types = [...new Set(p.units.flatMap(u => u.types ?? []))]
	return {
		address: p.id,
		metadata: { name: p.name, version: '0.1.0', spec: '0.1.0' },
		instructions: p.units.map(u => ({ name: u.name, discriminator: disc(`global:${u.name}`), accounts: idlAccounts(u.idl), args: u.args.map(([name, type]) => ({ name, type })) })),
		accounts: types.map(t => ({ name: t, discriminator: disc(`account:${t}`) })),
		errors: [...ERRORS, ...p.errors ?? []].map((e, i) => ({ code: 6000 + i, name: e[0].toLowerCase() + e.slice(1) })),
		types: types.map(t => ({ name: t, type: { kind: 'struct', fields: TYPES[t].fields.map(([name, ty]) => ({ name, type: IDL_TY[ty] })) } })),
	}
}

function expected(p: Program): any {
	const anchor = p.kind.startsWith('anchor')
	return {
		kind: anchor ? 'anchor' : 'native',
		...(anchor ? { idl: `${p.name}.json` } : {}),
		generated: true,
		about: `generated by bench/gen/gen.ts (${p.kind}): ${p.about}. Scored for rules only: every finding on the base is false, each variant expects one of its rules at its instruction ('~consistency': a validation_consistency inconsistency there).`,
		instructions: Object.fromEntries(p.units.map(u => [u.name, { ...(u.tag !== undefined ? { tag: u.tag } : {}), accounts: {} }])),
		...(p.units.some(u => u.fundMover) ? { fund_movers: p.units.filter(u => u.fundMover).map(u => ({ ix: u.name, ...u.fundMover })) } : {}),
		variants: Object.fromEntries(variantsOf(p).filter(v => !v.notExploitable).map(v => [v.id, { ix: v.ix, rules: v.rules, ...(v.idl ? { idl: { [v.ix]: v.idl } } : {}) }])),
		...(variantsOf(p).some(v => v.notExploitable) ? { discarded: Object.fromEntries(variantsOf(p).filter(v => v.notExploitable).map(v => [v.id, { ix: v.ix, reason: v.notExploitable }])) } : {}),
	}
}

const json = (x: any) => JSON.stringify(x, null, '\t').replace(/\[\n\t+([^\[\]{}]*?)\n\t+\]/g, (_, b: string) => `[${b.replace(/\n\t+/g, ' ')}]`) + '\n'

for (const p of PROGRAMS) {
	const ws = join(BENCH, 'gen', p.kind === 'anchor29' ? 'programs29' : 'programs')
	mkdirSync(join(ws, p.name, 'src'), { recursive: true })
	writeFileSync(join(ws, p.name, 'Cargo.toml'), cargoToml(p))
	writeFileSync(join(ws, p.name, 'src', 'lib.rs'), p.kind.startsWith('anchor') ? anchorLib(p) : nativeLib(p))
	if (p.kind.startsWith('anchor')) writeFileSync(join(BENCH, 'idl', p.name + '.json'), json(idl(p)))
	writeFileSync(join(BENCH, 'expected', p.name + '.json'), json(expected(p)))
	console.log(`${p.name}: ${p.units.length} instructions, ${variantsOf(p).length} variants`)
}
for (const [ws, members] of [['programs', PROGRAMS.filter(p => p.kind !== 'anchor29')], ['programs29', PROGRAMS.filter(p => p.kind === 'anchor29')]] as const) {
	const a29 = ws === 'programs29'
	writeFileSync(join(BENCH, 'gen', ws, 'Cargo.toml'), `# generated by bench/gen/gen.ts
[workspace]
resolver = "2"
members = [${members.map(p => `"${p.name}"`).join(', ')}]

[workspace.dependencies]
${a29 ? `anchor-lang = "=0.29.0"
anchor-spl = { version = "=0.29.0", default-features = false, features = ["token"] }
solana-program = "=1.16.27"` : `anchor-lang = "=0.31.1"
anchor-spl = { version = "=0.31.1", default-features = false, features = ["token", "token_2022", "token_2022_extensions"] }
solana-program = "=2.2.1"
spl-token = { version = "=8.0.0", features = ["no-entrypoint"] }
pinocchio = "=0.8.4"`}

[profile.release]
overflow-checks = true
lto = "fat"
codegen-units = 1
`)
}
