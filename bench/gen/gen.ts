// Generates the bench/gen programs from instruction templates (anchor.ts, native.ts): per program a crate (clean base,
// one cargo feature v_<id> per single-property variant), an Anchor IDL (bench/idl) and the expectation file
// (bench/expected, "generated": true: scored for rules only, bench/run.ts). Deterministic; rerun after editing a template,
// then build with `WS=bench/gen/programs sh bench/build.sh g_` (and programs29 for Anchor 0.29).
// usage: node bench/gen/gen.ts
import { createHash } from 'node:crypto'
import { mkdirSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { TYPES, vaultUnits, poolUnits, camel } from './anchor.ts'
import { bankHeader, bankUnits, ammHeader, ammUnits, jarHeader, jarUnits } from './native.ts'
import { riskAnchorHeader, riskAnchorUnits, riskNativeHeader, riskNativeUnits } from './risk.ts'

export interface Variant { id: string; rules: string[]; idl?: string; notExploitable?: string } // notExploitable: kept as a build, not scored (reason)
export interface Unit {
	name: string
	tag?: number // native: dispatch byte
	types?: string[] // Anchor account types used
	idl: string // Anchor: IDL accounts `name:ws …`
	args: [string, string][]
	code: string // Anchor: handler inside #[program]; native: the fn
	accounts?: string // Anchor: the Accounts struct (without #[derive(Accounts)])
	variants: Variant[]
	fundMover?: { authority: string; from: string; index?: number } // informational: an authority-only instruction moving user funds
}
export interface AccountType { fields: [string, string][] }
interface Program { name: string; kind: 'anchor29' | 'anchor31' | 'native' | 'pinocchio'; id?: string; about: string; header?: string; units: Unit[]; deps?: string[]; errors?: string[] }

const BENCH = join(dirname(fileURLToPath(import.meta.url)), '..')

